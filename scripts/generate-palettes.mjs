// تولید src/styles/palettes.css از src/lib/palettes.json
// اجرا: npm run palettes:generate  (خروجی با خطا تمام می‌شود اگر کنتراست WCAG AA رعایت نشود)
import { readFileSync, writeFileSync } from "node:fs";

const palettes = JSON.parse(readFileSync("src/lib/palettes.json", "utf8"));
const theme = readFileSync("node_modules/tailwindcss/theme.css", "utf8");

const oklch = {};
for (const m of theme.matchAll(/--color-([a-z]+)-(\d+):\s*oklch\(([\d.]+)%\s+([\d.]+)\s+([\d.]+|none)\)/g)) {
  oklch[`${m[1]}-${m[2]}`] = [Number(m[3]) / 100, Number(m[4]), m[5] === "none" ? 0 : Number(m[5])];
}

function toLinearRgb([L, C, h]) {
  const a = C * Math.cos((h * Math.PI) / 180);
  const b = C * Math.sin((h * Math.PI) / 180);
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  return [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ].map((v) => Math.min(1, Math.max(0, v)));
}
const luminance = (c) => {
  const [r, g, b] = toLinearRgb(c);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const WHITE = [1, 0, 0];
const contrast = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

const get = (name) => {
  if (name === "white") return WHITE;
  if (!oklch[name]) throw new Error(`Unknown Tailwind color: ${name}`);
  return oklch[name];
};
const ref = (name) => (name === "white" ? "#ffffff" : `var(--color-${name})`);

function pickStep(candidates, accent, against, fgOptions) {
  for (const step of candidates) {
    for (const fg of fgOptions) {
      if (contrast(get(`${accent}-${step}`), get(fg)) >= 4.5) return { step, fg };
    }
  }
  throw new Error(`No accessible step for ${accent}`);
}

const failures = [];
function check(id, mode, label, fg, bg) {
  const ratio = contrast(get(fg), get(bg));
  if (ratio < 4.5) failures.push(`${id}/${mode}: ${label} ${ratio.toFixed(2)} (${fg} on ${bg})`);
}

function tokens(p, mode) {
  const A = (s) => `${p.accent}-${s}`;
  const G = (s) => `${p.gray}-${s}`;
  let t;
  if (mode === "light") {
    const chosen = p.lightStep
      ? { step: p.lightStep, fg: contrast(get(A(p.lightStep)), WHITE) >= 4.5 ? "white" : G(950) }
      : pickStep([600, 700, 800], p.accent, "white", ["white"]);
    t = {
      background: "white", foreground: G(950),
      card: "white", "card-foreground": G(950),
      popover: "white", "popover-foreground": G(950),
      primary: A(chosen.step), "primary-foreground": chosen.fg,
      secondary: A(100), "secondary-foreground": A(900),
      muted: G(100), "muted-foreground": G(600),
      accent: A(100), "accent-foreground": A(900),
      destructive: "red-600",
      border: G(200), input: G(300), ring: A(400),
      selected: A(200), "selected-foreground": A(950),
    };
  } else {
    const chosen = p.darkStep
      ? { step: p.darkStep, fg: G(950) }
      : pickStep([400, 300], p.accent, "", [A(950), G(950)]);
    t = {
      background: G(950), foreground: G(50),
      card: G(900), "card-foreground": G(50),
      popover: G(900), "popover-foreground": G(50),
      primary: A(chosen.step), "primary-foreground": chosen.fg,
      secondary: A(900), "secondary-foreground": A(50),
      muted: G(800), "muted-foreground": G(400),
      accent: A(800), "accent-foreground": A(50),
      destructive: "red-400",
      border: G(800), input: G(700), ring: A(500),
      selected: A(700), "selected-foreground": A(50),
    };
  }
  for (const [label, fg, bg] of [
    ["foreground", "foreground", "background"], ["card", "card-foreground", "card"],
    ["popover", "popover-foreground", "popover"], ["primary", "primary-foreground", "primary"],
    ["secondary", "secondary-foreground", "secondary"], ["accent", "accent-foreground", "accent"],
    ["selected", "selected-foreground", "selected"], ["muted-fg/bg", "muted-foreground", "background"],
    ["muted-fg/muted", "muted-foreground", "muted"], ["muted-fg/card", "muted-foreground", "card"],
    ["destructive/bg", "destructive", "background"], ["destructive/card", "destructive", "card"],
    ["primary/bg", "primary", "background"],
  ]) {
    if (label === "primary/bg" && contrast(get(t.primary), get(t.background)) < 3) {
      failures.push(`${p.id}/${mode}: primary on background < 3:1`);
      continue;
    }
    if (label !== "primary/bg") check(p.id, mode, label, t[fg], t[bg]);
  }
  return t;
}

const block = (selector, t) =>
  `${selector} {\n${Object.entries(t).map(([k, v]) => `  --${k}: ${ref(v)};`).join("\n")}\n}\n`;

let css = `/* AUTO-GENERATED by scripts/generate-palettes.mjs from src/lib/palettes.json — do not edit. */\n\n`;
for (const p of palettes) {
  const light = tokens(p, "light");
  const dark = tokens(p, "dark");
  const lightSel = p.id === "neutral" ? `:root,\n:root[data-palette="neutral"]` : `:root[data-palette="${p.id}"]`;
  const darkSel = p.id === "neutral" ? `.dark,\n.dark[data-palette="neutral"]` : `.dark[data-palette="${p.id}"]`;
  css += `/* ${p.id} */\n${block(lightSel, light)}${block(darkSel, dark)}`;
  css += `[data-palette-swatch="${p.id}"] {\n  background-color: ${ref(light.primary)};\n}\n.dark [data-palette-swatch="${p.id}"] {\n  background-color: ${ref(dark.primary)};\n}\n\n`;
}
writeFileSync("src/styles/palettes.css", css);

if (failures.length) {
  console.error("WCAG AA failures:\n" + failures.join("\n"));
  process.exit(1);
}
console.log(`Generated ${palettes.length} palettes — all contrast checks passed (>= 4.5:1).`);
